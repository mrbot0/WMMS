@dataclass(frozen=True)
class Action:
    id: str
    area: str
    title: str
    description: str
    risk: str
    minutes: float
    run: Callable = field(repr=False, compare=False)
    warning: str = ""
    kind: str = "fix"  # "fix" changes the PC, "report" only reads it

    def as_dict(self) -> dict:
        data = asdict(self)
        del data["run"]
        return data


